interface I18nContextValue {
  language: AppLanguage;
  locale: 'en-US' | 'tr-TR';
  setLanguage: (language: AppLanguage) => void;
  t: (source: string, values?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18nContextValue | null>(null);

const getInitialLanguage = (): AppLanguage => {
  if (typeof window === 'undefined') return 'en';
  try {
    const storedLanguage = window.localStorage.getItem(LANGUAGE_STORAGE_KEY);
    if (storedLanguage === 'en' || storedLanguage === 'tr') return storedLanguage;
  } catch {
    // Storage can be unavailable in privacy-restricted browser contexts.
  }
  return window.navigator.language.toLocaleLowerCase().startsWith('tr') ? 'tr' : 'en';
};

export const I18nProvider: React.FC<React.PropsWithChildren> = ({ children }) => {
  const [language, updateLanguage] = useState<AppLanguage>(getInitialLanguage);

  const setLanguage = useCallback((nextLanguage: AppLanguage) => {
    updateLanguage(nextLanguage);
    try {
      window.localStorage.setItem(LANGUAGE_STORAGE_KEY, nextLanguage);
    } catch {
      // The in-memory choice still works when storage is unavailable.
    }
  }, []);

  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);

  const t = useCallback((source: string, values: Record<string, string | number> = {}) => {
    const template = language === 'tr' ? turkishTranslations[source] || source : source;
    return Object.entries(values).reduce(
      (translated, [key, value]) => translated.replaceAll(`{{${key}}}`, String(value)),
      template,
    );
  }, [language]);

  const value = useMemo<I18nContextValue>(() => ({
    language,
    locale: language === 'tr' ? 'tr-TR' : 'en-US',
    setLanguage,
    t,
  }), [language, setLanguage, t]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
};

export const useI18n = (): I18nContextValue => {
  const context = useContext(I18nContext);
  if (!context) throw new Error('useI18n must be used within an I18nProvider.');
  return context;
};
